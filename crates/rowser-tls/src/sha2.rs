//! SHA-256, SHA-384 and SHA-512 (FIPS 180-4 / RFC 6234).
//!
//! SHA-384 and SHA-512 share the SHA-512 compression function with
//! different IVs and output lengths.

/// Which hash a cipher suite or signature scheme uses.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum HashAlg {
    Sha256,
    Sha384,
    Sha512,
}

impl HashAlg {
    pub fn hash_len(self) -> usize {
        match self {
            HashAlg::Sha256 => 32,
            HashAlg::Sha384 => 48,
            HashAlg::Sha512 => 64,
        }
    }

    /// HMAC block size in bytes.
    pub fn block_size(self) -> usize {
        match self {
            HashAlg::Sha256 => 64,
            HashAlg::Sha384 | HashAlg::Sha512 => 128,
        }
    }

    pub fn hash(self, data: &[u8]) -> Vec<u8> {
        match self {
            HashAlg::Sha256 => sha256(data).to_vec(),
            HashAlg::Sha384 => sha384(data).to_vec(),
            HashAlg::Sha512 => sha512(data).to_vec(),
        }
    }
}

