//! CSS conformance corpus — computed-style assertions through the real
//! pipeline: `rowser_html::parse` → `document_sheets` → `StyleCtx::computed`.
//!
//! Each case renders a small HTML+CSS document and asserts the cascaded
//! value of one or more properties on a target element. The final
//! `conformance_rate` test is the gate: it reports every failure and
//! asserts the corpus-wide pass rate stays at/above the threshold.

use rowser_css::{document_sheets_vw, matches, parse_selector, StyleCtx};
use rowser_dom::{Document, NodeId};

struct C {
    name: &'static str,
    html: &'static str,
    /// selector for the element under test
    sel: &'static str,
    /// (property, expected computed value)
    checks: &'static [(&'static str, &'static str)],
}

fn q(doc: &Document, sel: &str) -> NodeId {
    let s = parse_selector(sel).unwrap_or_else(|| panic!("bad selector {sel}"));
    doc.descendants(doc.root)
        .find(|&n| matches(doc, n, &s))
        .unwrap_or_else(|| panic!("no node matches {sel}"))
}

